-- Locales/en.lua: English source text of the core. Every line has a stable id; Locales/ja.lua translates the same
-- ids. Skill, talent and guide texts and the class-specific interface lines live in the class packs
-- (ForeverSensei_<Class>/Locales/*.lua, looked up first). Facts come from WoW: Forever sources only (see SOURCES.md).
-- Placeholders are {name}; the Japanese must use the same ones.
local _, ns = ...

ns.Locales = ns.Locales or {}
ns.LocaleOrder = {}
local data = {}
ns.Locales.en = data
-- Proxy that records the order of ids (the review tab walks them in this order).
local L = setmetatable({}, { __newindex = function(_, k, v)
  if data[k] == nil then table.insert(ns.LocaleOrder, k) end
  data[k] = v
end })

